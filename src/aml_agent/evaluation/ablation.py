"""Compare tagged benchmark runs.

Reads results/retrieval_<tag>.json for each tag and writes a side-by-side
comparison. Used for the embedding-model ablation, but tag-agnostic: anything
that can be varied while holding the rest constant can be compared this way.

The BM25 row is the control. It does not depend on the embedding model, so if
it moves between runs the experiment leaked and the comparison is void.
"""

from __future__ import annotations

import json
import sys
from typing import Any

from ..config import settings

METRICS = (
    ("recall_at_5", "Recall@5"),
    ("recall_at_10", "Recall@10"),
    ("mrr", "MRR"),
)
ROWS = ("bm25", "dense", "hybrid", "hybrid+rerank")
LABELS = {
    "bm25": "Lexical (BM25) — control",
    "dense": "Dense",
    "hybrid": "Hybrid (RRF)",
    "hybrid+rerank": "Hybrid + rerank",
}


def _load(tag: str) -> dict[str, Any]:
    path = settings.results_dir / f"retrieval_{tag}.json"
    if not path.exists():
        raise FileNotFoundError(
            f"{path} not found. Produce it with "
            f"`eval-retrieval --tag {tag}` under the configuration you want to compare."
        )
    return json.loads(path.read_text(encoding="utf-8"))


def _fmt_delta(value: float) -> str:
    if abs(value) < 1e-9:
        return "—"
    return f"{value:+.3f}"


def build(tags: list[str]) -> str:
    runs = {tag: _load(tag) for tag in tags}
    profile = runs[tags[0]].get("authoring_profile", "t480")

    out: list[str] = [
        "# Embedding-model ablation",
        "",
        "Generated by `make eval-ablation`. One variable changes between runs: "
        "the embedding model. Chunk boundaries are computed with a fixed "
        "reference tokenizer precisely so that they do not move when the model "
        "does — otherwise this would compare model-A-with-A's-chunking against "
        "model-B-with-B's-chunking, which is two variables and no conclusion.",
        "",
        f"Profile `{profile}`, exact gold, {runs[tags[0]]['questions']} questions.",
        "",
    ]

    for tag in tags:
        settings_used = runs[tag]["settings"]
        out.append(
            f"- **{tag}** — `{settings_used.get('embedding_model')}`, "
            f"{settings_used.get('embedding_dim')}d"
        )
    out.append("")

    header = "| Retriever | Metric | " + " | ".join(tags) + " | Δ |"
    out += [header, "|" + "---|" * (len(tags) + 3)]

    for row in ROWS:
        for key, label in METRICS:
            values = []
            for tag in tags:
                entry = runs[tag]["profiles"].get(profile, {}).get(row, {}).get("exact")
                values.append(entry[key] if entry else None)
            if any(v is None for v in values):
                continue
            delta = values[-1] - values[0]
            cells = " | ".join(f"{v:.3f}" for v in values)
            out.append(f"| {LABELS[row]} | {label} | {cells} | {_fmt_delta(delta)} |")

    # The ceiling is the headline: it says whether the candidate pool improved,
    # which is the thing the reranker cannot fix.
    ceilings = []
    for tag in tags:
        entry = runs[tag]["profiles"].get(profile, {}).get("hybrid+rerank", {})
        ceiling = entry.get("first_stage_ceiling")
        ceilings.append(ceiling["recall"] if ceiling else None)
    if all(c is not None for c in ceilings):
        cells = " | ".join(f"{c:.3f}" for c in ceilings)
        out.append(
            f"| First-stage ceiling@50 | recall | {cells} | "
            f"{_fmt_delta(ceilings[-1] - ceilings[0])} |"
        )

    out += [
        "",
        "## Reading this",
        "",
        "**BM25 is the control.** It does not use embeddings, so it must be "
        "identical across runs. If it moves, the experiment leaked and nothing "
        "else in the table can be trusted.",
        "",
        "**The ceiling is the number that matters.** The candidate sweep showed "
        "the reranker already uses 100% of the headroom it is given, so the only "
        "way to improve the final answer is to put more gold passages into the "
        "candidate pool. A ceiling that moves is a real gain; a ceiling that does "
        "not is a reshuffle.",
    ]
    return "\n".join(out)


def main() -> int:
    tags = [a for a in sys.argv[1:] if not a.startswith("-")]
    if len(tags) < 2:
        print("usage: python -m aml_agent.evaluation.ablation <tag-a> <tag-b> [...]")
        return 2

    output = settings.results_dir / "embedding_ablation.md"
    output.write_text(build(tags), encoding="utf-8", newline="\n")
    print(f"wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
