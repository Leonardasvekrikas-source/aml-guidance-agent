"""Compare tagged benchmark runs.

Reads results/retrieval_<tag>.json for each tag and writes a side-by-side
comparison. Tag-agnostic: anything that can be varied while holding the rest
constant can be compared this way. Used for the embedding-model swap and for
contextual retrieval.

Whether BM25 acts as a control depends on what the ablation changed, which is
why the interpretation is passed in per comparison rather than hardcoded here.
Swapping the embedding model leaves the indexed text untouched, so BM25 must
not move and a move means the experiment leaked. Contextual retrieval changes
the indexed text itself, so BM25 moving is the intended effect. Asserting the
first in a report showing the second would contradict the table above it.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from ..config import settings

METRICS = (
    ("recall_at_5", "Recall@5"),
    ("recall_at_10", "Recall@10"),
    ("mrr", "MRR"),
)
ROWS = ("bm25", "dense", "hybrid", "hybrid+rerank")
LABELS = {
    "bm25": "Lexical (BM25)",
    "dense": "Dense",
    "hybrid": "Hybrid (RRF)",
    "hybrid+rerank": "Hybrid + rerank",
}


def _load(tag: str) -> dict[str, Any]:
    path = settings.results_dir / f"retrieval_{tag}.json"
    if not path.exists():
        raise FileNotFoundError(
            f"{path} not found. Produce it with "
            f"`eval-retrieval --tag {tag}` under the configuration you want to compare."
        )
    return json.loads(path.read_text(encoding="utf-8"))


def _raw_entry(run: dict[str, Any], retriever: str) -> dict[str, Any]:
    """The retriever's block, whichever single profile this run measured."""
    profiles = run.get("profiles", {})
    for data in profiles.values():
        if retriever in data:
            return data[retriever]
    return {}


def _entry(run: dict[str, Any], retriever: str) -> dict[str, Any] | None:
    return _raw_entry(run, retriever).get("exact")


def _fmt_delta(value: float) -> str:
    if abs(value) < 1e-9:
        return "—"
    return f"{value:+.3f}"


# Whether BM25 is a control depends on what the ablation changed, so the
# interpretation is passed in rather than assumed. Swapping the embedding model
# leaves the indexed text untouched, so BM25 must not move. Changing the text
# itself — as contextual retrieval does — moves BM25 legitimately, and
# asserting otherwise would contradict the table printed directly above it.
DEFAULT_READING = (
    "**The ceiling is the number that matters.** It is the fraction of gold "
    "passages that reach the candidate pool at all, and the reranker cannot "
    "exceed it. A ceiling that moves is a real gain; a ceiling that does not "
    "is a reshuffle."
)


def build(
    tags: list[str],
    title: str = "Ablation",
    note: str = "",
    reading: str = "",
) -> str:
    runs = {tag: _load(tag) for tag in tags}
    profile = runs[tags[0]].get("authoring_profile", "t480")

    out: list[str] = [
        f"# {title}",
        "",
        note
        or (
            "Generated by `make eval-ablation`. One variable changes between "
            "runs. Chunk boundaries come from a fixed reference tokenizer so "
            "that they do not move when anything else does."
        ),
        "",
        f"Exact gold, {runs[tags[0]]['questions']} questions.",
        "",
    ]

    for tag in tags:
        settings_used = runs[tag]["settings"]
        out.append(
            f"- **{tag}** — `{settings_used.get('embedding_model')}`, "
            f"{settings_used.get('embedding_dim')}d"
        )
    out.append("")

    header = "| Retriever | Metric | " + " | ".join(tags) + " | Δ |"
    out += [header, "|" + "---|" * (len(tags) + 3)]

    for row in ROWS:
        for key, label in METRICS:
            values: list[float] = []
            complete = True
            for tag in tags:
                entry = _entry(runs[tag], row)
                if not entry:
                    # A retriever measured in one run and not another cannot be
                    # compared, so the row is omitted rather than half-filled.
                    complete = False
                    break
                values.append(float(entry[key]))

            if not complete:
                continue

            delta = values[-1] - values[0]
            cells = " | ".join(f"{v:.3f}" for v in values)
            out.append(f"| {LABELS[row]} | {label} | {cells} | {_fmt_delta(delta)} |")

    # The ceiling is the headline: it says whether the candidate pool improved,
    # which is the thing the reranker cannot fix.
    ceilings: list[float] = []
    for tag in tags:
        entry = _raw_entry(runs[tag], "hybrid+rerank")
        ceiling = entry.get("first_stage_ceiling")
        if ceiling:
            ceilings.append(float(ceiling["recall"]))

    if len(ceilings) == len(tags):
        cells = " | ".join(f"{c:.3f}" for c in ceilings)
        out.append(
            f"| First-stage ceiling@50 | recall | {cells} | "
            f"{_fmt_delta(ceilings[-1] - ceilings[0])} |"
        )

    out += ["", "## Reading this", "", reading or DEFAULT_READING]
    return "\n".join(out)


def main() -> int:
    # Positional tags only: a value that follows a flag belongs to the flag,
    # not to the tag list.
    flags_with_values = {"--title", "--note", "--out", "--reading", "--reading-file"}
    tags: list[str] = []
    skip_next = False
    for arg in sys.argv[1:]:
        if skip_next:
            skip_next = False
            continue
        if arg in flags_with_values:
            skip_next = True
            continue
        if arg.startswith("-"):
            continue
        tags.append(arg)
    if len(tags) < 2:
        print("usage: python -m aml_agent.evaluation.ablation <tag-a> <tag-b> [...]")
        return 2

    def flag(name: str, default: str) -> str:
        return sys.argv[sys.argv.index(name) + 1] if name in sys.argv else default

    # --reading-file takes a path, because the interpretation runs to several
    # paragraphs and a shell argument that long is unwieldy and easy to mangle.
    reading = flag("--reading", "")
    reading_file = flag("--reading-file", "")
    if reading_file:
        reading = Path(reading_file).read_text(encoding="utf-8").strip()

    output = settings.results_dir / flag("--out", "embedding_ablation.md")
    output.write_text(
        build(tags, flag("--title", "Ablation"), flag("--note", ""), reading),
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
