"""Per-question analysis of the retrieval benchmark.

An averaged table tells you which retriever won. It does not tell you why, and
"hybrid is better" is not an answer anyone should accept without a case.

This writes results/retrieval_analysis.md: the questions where lexical beats
dense, where dense beats lexical, and — the ones worth reading closely — where
fusion is worse than the better of its two inputs. RRF is not free, and a
benchmark that only reports its wins is advertising.
"""

from __future__ import annotations

import json
from typing import Any

from ..config import settings

METRIC = "reciprocal_rank"  # exact gold, on the authoring profile
PAGE_METRIC = "page_reciprocal_rank"


def _rows(data: dict[str, Any], profile: str, retriever: str) -> dict[str, dict[str, Any]]:
    return {r["question_id"]: r for r in data["profiles"][profile][retriever]["per_question"]}


def build(data: dict[str, Any]) -> str:
    profile = data.get("authoring_profile", "t480")
    bm25 = _rows(data, profile, "bm25")
    dense = _rows(data, profile, "dense")
    hybrid = _rows(data, profile, "hybrid")

    metric = METRIC if METRIC in next(iter(bm25.values())) else PAGE_METRIC

    lexical_wins: list[tuple[float, str, dict]] = []
    dense_wins: list[tuple[float, str, dict]] = []
    fusion_losses: list[tuple[float, str, dict]] = []

    for qid, row in bm25.items():
        b = row[metric]
        d = dense[qid][metric]
        h = hybrid[qid][metric]

        if b > d:
            lexical_wins.append((b - d, qid, row))
        elif d > b:
            dense_wins.append((d - b, qid, row))

        best_single = max(b, d)
        if h < best_single - 1e-9:
            fusion_losses.append((best_single - h, qid, row))

    lexical_wins.sort(reverse=True)
    dense_wins.sort(reverse=True)
    fusion_losses.sort(reverse=True)

    def section(title: str, items: list, note: str) -> list[str]:
        lines = [f"## {title}", "", note, ""]
        if not items:
            lines += ["_None._", ""]
            return lines
        lines += ["| Question | Topic | BM25 RR | Dense RR | Hybrid RR |", "|---|---|---|---|---|"]
        for _, qid, row in items[:8]:
            question = row.get("topic") or qid
            lines.append(
                f"| `{qid}` | {question} | {bm25[qid][metric]:.3f} | "
                f"{dense[qid][metric]:.3f} | {hybrid[qid][metric]:.3f} |"
            )
        lines.append("")
        return lines

    out: list[str] = [
        "# Retrieval analysis, per question",
        "",
        f"Generated by `make eval-analysis` from `results/retrieval.json`. "
        f"Profile `{profile}`, metric: reciprocal rank (1 / rank of the first "
        f"gold passage; 0 if none was retrieved).",
        "",
        f"- Questions where lexical beat dense: **{len(lexical_wins)}**",
        f"- Questions where dense beat lexical: **{len(dense_wins)}**",
        f"- Questions where fusion was worse than its better input: **{len(fusion_losses)}**",
        "",
    ]

    out += section(
        "Where BM25 beats dense",
        lexical_wins,
        "These questions carry distinctive regulatory vocabulary that appears "
        "verbatim in the corpus. BM25 is very strong on rare exact tokens: a "
        "term with high inverse document frequency pins the passage almost by "
        "itself. An embedding places such a term near its semantic neighbours, "
        "which is exactly the wrong behaviour when the neighbours are other "
        "regulatory jargon that happens to be about something else.",
    )

    out += section(
        "Where dense beats BM25",
        dense_wins,
        "These questions were deliberately written in an analyst's own words "
        "rather than the document's phrasing. Lexical retrieval has nothing to "
        "match on when the question and the passage share meaning but not "
        "vocabulary.",
    )

    out += section(
        "Where fusion loses to its better input",
        fusion_losses,
        "RRF has a real cost, and this is it. When one retriever is confidently "
        "right and the other is confidently wrong, fusion drags the correct "
        "passage down the ranking by promoting chunks the losing retriever "
        "ranked highly. Fusion buys robustness across question types at the "
        "price of the best case on any single one.",
    )

    return "\n".join(out)


def main() -> int:
    path = settings.results_dir / "retrieval.json"
    if not path.exists():
        print("no results/retrieval.json — run `make eval-retrieval` first")
        return 1

    data = json.loads(path.read_text(encoding="utf-8"))
    output = settings.results_dir / "retrieval_analysis.md"
    output.write_text(build(data), encoding="utf-8", newline="\n")
    print(f"wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
