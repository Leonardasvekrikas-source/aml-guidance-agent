"""Rewrite the README results tables from results/*.json.

The README makes a promise — every number in it is regenerated by a committed
script. This is that script. It rewrites only the regions between the marker
comments, so prose around the tables is preserved and the numbers cannot drift
away from the artifacts they came from.

If a results file is missing, the corresponding table is written as "not yet
run" rather than left with stale figures from a previous corpus.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from ..config import settings

RETRIEVAL_START = "<!-- BEGIN retrieval-table -->"
RETRIEVAL_END = "<!-- END retrieval-table -->"
ANSWER_START = "<!-- BEGIN answer-table -->"
ANSWER_END = "<!-- END answer-table -->"
CORPUS_START = "<!-- BEGIN corpus-line -->"
CORPUS_END = "<!-- END corpus-line -->"

LABELS = {"bm25": "Lexical (BM25)", "dense": "Dense (pgvector)", "hybrid": "Hybrid (RRF)"}


def _load(name: str) -> dict[str, Any] | None:
    path = settings.results_dir / name
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def _fmt(value: Any, digits: int = 3) -> str:
    if value is None:
        return "–"
    return f"{value:.{digits}f}"


def retrieval_table() -> str:
    data = _load("retrieval.json")
    if not data:
        return (
            "_Not yet run._ Regenerate with `make eval-retrieval` "
            "(`.\\run.ps1 eval-retrieval` on Windows)."
        )

    profiles = data["profiles"]
    authoring = data.get("authoring_profile", "t480")
    lines: list[str] = []

    # Primary table: exact chunk-id gold, on the authoring profile only.
    lines.append(f"**Exact gold, chunk profile `{authoring}`** — the primary result.")
    lines.append("")
    lines.append("| Method | Recall@5 | Recall@10 | MRR | Hit@5 |")
    lines.append("|---|---|---|---|---|")
    for key in ("bm25", "dense", "hybrid"):
        row = profiles.get(authoring, {}).get(key, {}).get("exact")
        if not row:
            continue
        lines.append(
            f"| {LABELS[key]} | {_fmt(row['recall_at_5'])} | "
            f"{_fmt(row['recall_at_10'])} | {_fmt(row['mrr'])} | "
            f"{_fmt(row['hit_at_5'])} |"
        )
    lines.append("")
    lines.append(
        "A retrieved chunk counts only if it is literally the gold chunk. "
        "Recall is per-question recall over the gold set, not hit-rate; Hit@5 "
        "is shown beside it so the difference is visible rather than hidden by "
        "a label."
    )
    lines.append("")

    # Chunk-size comparison: page-level gold, the only profile-independent one.
    lines.append("**Chunk-size comparison, page-level gold**")
    lines.append("")
    lines.append("| Profile | Method | Recall@5 | Recall@10 | MRR | Median latency |")
    lines.append("|---|---|---|---|---|---|")
    for profile_name in sorted(profiles):
        for key in ("bm25", "dense", "hybrid"):
            entry = profiles[profile_name].get(key)
            if not entry:
                continue
            row = entry["page_level"]
            lines.append(
                f"| `{profile_name}` | {LABELS[key]} | {_fmt(row['recall_at_5'])} | "
                f"{_fmt(row['recall_at_10'])} | {_fmt(row['mrr'])} | "
                f"{entry['median_latency_ms']:.0f} ms |"
            )
    lines.append("")
    lines.append(
        "Gold chunk ids belong to the profile the questions were authored "
        f"against (`{authoring}`), and chunks are separate rows per profile, so "
        "chunk-id gold cannot compare chunk sizes at all. Page-level gold — did "
        "retrieval return a chunk from a page the answer is on — is "
        "profile-independent and is the only definition under which this "
        "comparison means anything. It is looser than exact gold, so the two "
        "tables must not be compared with each other."
    )
    lines.append("")
    lines.append(
        f"Computed over {data['questions']} answerable questions with "
        "hand-authored gold passages."
    )
    return "\n".join(lines)


def answer_table() -> str:
    data = _load("answers.json")
    if not data:
        return (
            "_Not yet run._ Requires an `ANTHROPIC_API_KEY`. Regenerate with "
            "`make eval-answers`."
        )

    metrics = data["metrics"]
    counts = data["counts"]
    latency = metrics.get("median_latency_ms")

    lines = [
        "| Metric | Value |",
        "|---|---|",
        f"| Groundedness — claims supported by retrieved text | {_fmt(metrics['groundedness'])} |",
        f"| Citation validity — cited passage was actually retrieved | {_fmt(metrics['citation_validity'])} |",
        f"| Refusal accuracy on unanswerable questions | {_fmt(metrics['refusal_accuracy'])} |",
        f"| Answer rate on answerable questions | {_fmt(metrics['answer_rate'])} |",
        f"| Median latency | {'–' if latency is None else f'{latency / 1000:.1f} s'} |",
        f"| Median retrieval calls per question | {metrics.get('median_searches', '–')} |",
        "",
        f"Over {counts['answerable']} answerable and {counts['unanswerable']} "
        f"unanswerable questions; {counts['judged']} answers were judged for "
        "groundedness.",
        "",
        "Answer rate is reported next to groundedness deliberately. A system "
        "that refuses every question scores perfect groundedness and is useless; "
        "the two numbers only mean something together.",
    ]
    return "\n".join(lines)


def corpus_line() -> str:
    data = _load("corpus.json")
    if not data:
        return "_Corpus not yet ingested._"

    profiles = data.get("profiles", [])
    parts = ", ".join(
        f"{p['chunks']} chunks at profile `{p['chunk_profile']}`" for p in profiles
    )
    return (
        f"Corpus: **{data['documents']} documents** from "
        f"{len(data.get('by_publisher', []))} publishers — {parts}."
    )


def replace_region(text: str, start: str, end: str, body: str) -> str:
    if start not in text or end not in text:
        raise ValueError(
            f"README is missing the marker pair {start} / {end}. The report "
            "generator only rewrites marked regions so it cannot clobber prose."
        )
    head = text.split(start)[0]
    tail = text.split(end)[1]
    return f"{head}{start}\n{body}\n{end}{tail}"


def main() -> int:
    readme = Path(settings.manifest_path).parents[1] / "README.md"
    text = readme.read_text(encoding="utf-8")

    text = replace_region(text, CORPUS_START, CORPUS_END, corpus_line())
    text = replace_region(text, RETRIEVAL_START, RETRIEVAL_END, retrieval_table())
    text = replace_region(text, ANSWER_START, ANSWER_END, answer_table())

    readme.write_text(text, encoding="utf-8", newline="\n")
    print(f"rewrote the results tables in {readme.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
